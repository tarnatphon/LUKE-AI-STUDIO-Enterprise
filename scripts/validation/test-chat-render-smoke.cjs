#!/usr/bin/env node
"use strict";

/**
 * The Chat and Work tabs broke twice, and both times the whole panel was
 * replaced by "Workspace could not be loaded" plus a minified ReferenceError.
 * Nothing caught them: esbuild compiles a temporal-dead-zone read without an
 * objection, and every suite before this one read source instead of running it.
 *
 * So this suite runs the real component. Vite builds a small SSR entry that
 * imports TextChat, the test installs a jsdom window (localStorage and
 * matchMedia are read during render), and react-dom/server executes the render
 * pass for both tabs — the pass that died. Effects are not run and nothing is
 * fetched: a fetch stub answers anything that slips through.
 *
 * A canary component with a deliberate dead-zone read is rendered too. If the
 * canary does not fail, the harness is not executing what it claims to, and the
 * suite says so rather than reporting a comfortable pass.
 *
 * Run: node scripts/validation/test-chat-render-smoke.cjs
 */

const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { pathToFileURL } = require("node:url");

const root = path.resolve(__dirname, "..", "..");
const frontend = path.join(root, "app", "frontend");
const outDir = path.join(os.tmpdir(), `luke-chat-smoke-${process.pid}`);
// The entry has to sit inside app/frontend, or its own `import "react"` resolves
// against a folder with no node_modules. It is written per run and deleted.
const entry = path.join(frontend, `.chat-render-entry-${process.pid}.js`);

const ENTRY_SOURCE = `// Generated by scripts/validation/test-chat-render-smoke.cjs — deleted after the run.
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import TextChat from "./src/components/TextChat.jsx";

// Executes the render pass of the real component: the pass that shipped two
// ReferenceErrors. Effects and API calls are not reached.
export function renderChat(props) {
  return renderToStaticMarkup(createElement(TextChat, props));
}

// The same mistake on purpose, so the suite can prove it would notice.
function TdzCanary() {
  const first = second;
  const second = "never";
  return createElement("div", null, first);
}

export function renderCanary() {
  return renderToStaticMarkup(createElement(TdzCanary));
}
`;

let checks = 0;
function assert(condition, message) {
  if (!condition) throw new Error(`FAIL: ${message}`);
  checks += 1;
  console.log(`  ✓ ${message}`);
}

const modulePath = (name) => path.join(frontend, "node_modules", name);

async function buildEntry() {
  const vite = await import(pathToFileURL(modulePath("vite/dist/node/index.js")).href);
  const reactPlugin = JSON.parse(
    fs.readFileSync(modulePath("@vitejs/plugin-react/package.json"), "utf8"),
  );
  const reactEntry = typeof reactPlugin.exports?.["."] === "string"
    ? reactPlugin.exports["."]
    : (reactPlugin.module || reactPlugin.main || "dist/index.js");
  const react = await import(pathToFileURL(modulePath(path.join("@vitejs/plugin-react", reactEntry))).href);
  await vite.build({
    root: frontend,
    configFile: false, // the app's config copies pdf.js data and writes build-info; not wanted here
    logLevel: "silent",
    plugins: [(react.default || react)()],
    // The bundle is written to a temp folder, where node_modules is not on the
    // resolution path, so react and its friends have to travel with it.
    ssr: { noExternal: true, target: "node" },
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
    build: {
      ssr: entry,
      outDir,
      emptyOutDir: true,
      minify: false,
      target: "node20",
    },
  });
  const built = fs.readdirSync(outDir).filter((name) => /\.m?js$/.test(name) && !name.startsWith("sw"));
  assert(built.length > 0, `vite built the render entry (${built.join(", ") || "nothing"})`);
  return path.join(outDir, built[0]);
}

function installDom() {
  const { JSDOM } = require(modulePath("jsdom"));
  const dom = new JSDOM("<!doctype html><html><body><div id=\"root\"></div></body></html>", {
    url: "http://localhost:1420/",
    pretendToBeVisual: true,
  });
  const { window } = dom;

  // Node 22 ships its own `navigator`, defined as a getter, so plain
  // assignment throws; everything here goes through the same door.
  const define = (name, value) => {
    Object.defineProperty(globalThis, name, { value, configurable: true, writable: true });
  };

  define("window", window);
  define("document", window.document);
  define("navigator", window.navigator);
  define("localStorage", window.localStorage);
  define("sessionStorage", window.sessionStorage);
  define("HTMLElement", window.HTMLElement);
  define("Element", window.Element);
  define("Node", window.Node);
  define("Event", window.Event);
  define("CustomEvent", window.CustomEvent);
  define("getComputedStyle", window.getComputedStyle.bind(window));
  define("requestAnimationFrame", (callback) => window.setTimeout(() => callback(Date.now()), 0));
  define("cancelAnimationFrame", (id) => window.clearTimeout(id));
  if (!window.matchMedia) {
    window.matchMedia = () => ({
      matches: false,
      media: "",
      addEventListener() {},
      removeEventListener() {},
      addListener() {},
      removeListener() {},
    });
  }
  define("matchMedia", window.matchMedia);
  for (const name of ["ResizeObserver", "IntersectionObserver"]) {
    if (!window[name]) {
      window[name] = class {
        observe() {}
        unobserve() {}
        disconnect() {}
        takeRecords() { return []; }
      };
    }
    define(name, window[name]);
  }
  // Nothing here talks to a server. A promise that never settles keeps a stray
  // effect from turning into an unhandled rejection during the render.
  define("fetch", () => new Promise(() => {}));
  return dom;
}

function propsFor(assistantMode) {
  const noop = () => {};
  return {
    specs: { cpu: "Apple M3", ramGb: 18, gpus: [{ name: "Apple M3", vramGb: 14 }] },
    showAlert: noop,
    showConfirm: async () => true,
    textSettings: { temperature: 0.7, maxTokens: 1024, contextSize: 8192, responseTokenMode: "auto" },
    setTextSettings: noop,
    setActiveModel: noop,
    setServerRunning: noop,
    conversations: [],
    setConversations: noop,
    activeConversationId: "smoke-conversation",
    setActiveConversationId: noop,
    showHistory: false,
    setShowHistory: noop,
    saveConversationState: noop,
    setIsLlmLoaded: noop,
    assistantMode,
    activeProject: null,
    setProjects: noop,
    speechSettings: {},
  };
}

async function main() {
  console.log("=== Chat render smoke test ===\n");

  for (const required of ["vite", "react", "@vitejs/plugin-react", "jsdom"]) {
    assert(fs.existsSync(modulePath(required)), `${required} is installed (npm ci --prefix app/frontend)`);
  }

  fs.writeFileSync(entry, ENTRY_SOURCE, "utf8");
  const bundle = await buildEntry();
  const dom = installDom();

  const harness = await import(pathToFileURL(bundle).href);
  assert(typeof harness.renderChat === "function", "the harness exports the component it built");

  for (const mode of ["chat", "work"]) {
    let markup = "";
    let failure = "";
    try {
      markup = harness.renderChat(propsFor(mode));
    } catch (error) {
      failure = `${error && error.message}\n${error && error.stack ? error.stack.split("\n").slice(0, 4).join("\n") : ""}`;
    }
    assert(!failure, `the ${mode} tab renders without throwing${failure ? `\n${failure}` : ""}`);
    assert(markup.length > 200, `and produces markup (${markup.length} chars) for ${mode}`);
  }

  // The render pass must have really run: the composer is in the output.
  const chatMarkup = harness.renderChat(propsFor("chat"));
  assert(
    /textarea|contenteditable|placeholder=/i.test(chatMarkup),
    "the composer is in the rendered output, so this is the real component and not a fallback",
  );

  // Sensitivity: the same harness must catch a dead-zone read.
  let canary = "";
  try {
    harness.renderCanary();
  } catch (error) {
    canary = String(error && error.message);
  }
  assert(
    /before initialization/.test(canary),
    `a deliberate dead-zone read fails here (${canary || "nothing was thrown"})`,
  );

  dom.window.close();
  console.log(`\nPASS: ${checks} checks — the Chat and Work render passes run, and the harness bites.`);
}

main()
  .catch((error) => {
    console.error(`\n${error.message}`);
    process.exitCode = 1;
  })
  .finally(() => {
    fs.rmSync(outDir, { recursive: true, force: true });
    fs.rmSync(entry, { force: true });
  });
